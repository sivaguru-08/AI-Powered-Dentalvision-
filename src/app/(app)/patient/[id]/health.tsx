import { router, useLocalSearchParams } from 'expo-router';
import { Pressable, View } from 'react-native';

import { HealthHeatmap } from '@/components/dental/HealthHeatmap';
import { PatientNav } from '@/components/layout/PatientNav';
import { SimulationBanner } from '@/components/ui/Disclaimer';
import { Card, ProgressBar, SectionHeader } from '@/components/ui/primitives';
import { ScoreRing } from '@/components/ui/ScoreRing';
import { AppHeader, Screen, useLayout } from '@/components/ui/Screen';
import { ErrorState, LoadingState } from '@/components/ui/StateViews';
import { Text } from '@/components/ui/Text';
import { ALL_TEETH } from '@/domain/fdi';
import { usePatient } from '@/state/data';
import { fonts, radius, scoreColor, space, usePalette } from '@/theme';

export default function ToothHealthView() {
  const p = usePalette();
  const { isWide } = useLayout();
  const { id } = useLocalSearchParams<{ id: string }>();
  const { data: pt, loading, error, reload } = usePatient(id);
  const open = (n: string) => router.push({ pathname: '/patient/[id]/tooth/[tooth]', params: { id, tooth: n } });

  return (
    <Screen
      header={
        <AppHeader
          back={{ pathname: '/patient/[id]', params: { id } }}
          overline={pt ? `Patient ${pt.code} · ${pt.name}` : 'Patient'}
          title="Overall Tooth Health"
          subtitle="Simulated health index for every tooth"
        />
      }>
      <PatientNav current="health" />
      {error ? <ErrorState error={error} onRetry={reload} /> : null}
      {loading || !pt ? (
        !error ? <LoadingState label="Computing health map…" /> : null
      ) : (
        <>
          <SimulationBanner />
          <Card style={{ gap: space.lg }}>
            <View style={{ flexDirection: 'row', alignItems: 'center', gap: space.lg }}>
              <ScoreRing score={pt.dentalHealthIndex} size={84} stroke={8} />
              <View style={{ flex: 1 }}>
                <Text variant="h3">Health heatmap</Text>
                <Text variant="bodySm" tone="muted">
                  Teeth needing attention stand out immediately. Tap any cell to inspect.
                </Text>
              </View>
            </View>
            <HealthHeatmap teeth={pt.teeth} onSelect={open} />
          </Card>

          <Card style={{ gap: space.md }}>
            <SectionHeader title="All teeth" subtitle="FDI order · score out of 100" icon="list-outline" />
            <View style={{ flexDirection: 'row', flexWrap: 'wrap', columnGap: space.xl }}>
              {ALL_TEETH.map((n) => {
                const t = pt.teeth.find((x) => x.toothNumber === n)!;
                const s = t.healthIndex;
                return (
                  <Pressable
                    key={n}
                    onPress={() => open(n)}
                    style={({ pressed }) => ({
                      width: isWide ? '47%' : '100%',
                      flexDirection: 'row',
                      alignItems: 'center',
                      gap: space.md,
                      paddingVertical: 8,
                      borderBottomWidth: 1,
                      borderBottomColor: p.border,
                      opacity: pressed ? 0.7 : 1,
                    })}>
                    <Text style={{ width: 30, fontFamily: fonts.bold, fontSize: 14, color: p.text }}>{n}</Text>
                    <View style={{ flex: 1 }}>
                      <ProgressBar value={s ?? 0} color={scoreColor(p, s)} height={8} />
                    </View>
                    <Text style={{ width: 34, textAlign: 'right', fontFamily: fonts.bold, fontSize: 14, color: scoreColor(p, s) }}>{s ?? '—'}</Text>
                    <View style={{ width: 96 }}>
                      <Text variant="caption" tone={t.finding ? 'default' : 'faint'} numberOfLines={1}>
                        {t.finding?.shortTitle ?? (s == null ? 'Not assessed' : 'Healthy')}
                      </Text>
                    </View>
                  </Pressable>
                );
              })}
            </View>
          </Card>
          <View style={{ padding: space.md, borderRadius: radius.md, backgroundColor: p.surfaceAlt }}>
            <Text variant="caption" tone="muted">
              Scores are simulated demo metrics generated by the pilot and are not a validated clinical index.
            </Text>
          </View>
        </>
      )}
    </Screen>
  );
}
